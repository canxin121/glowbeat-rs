#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn overlapping_sections_are_rejected() {
        let mut score = LightingScore::empty(48_000, 2, 256);
        score.duration_samples = 96_000;
        let section = SectionCue {
            start_sample: 0,
            end_sample: 60_000,
            scene: SceneKind::Groove,
            repeat_group: 0,
            intensity: 0.5,
            palette_hue: 0.7,
            palette_chroma: 0.8,
            spatial_mode: SpatialMode::Wave,
            motif_seed: 42,
            anticipation_samples: 0,
            blackout_strength: 0.0,
            narrative_rank: 0.5,
        };
        score.sections.push(section.clone());
        score.sections.push(SectionCue {
            start_sample: 48_000,
            end_sample: 96_000,
            ..section
        });
        assert!(score.validate().is_err());
        assert!(score.write_to(&mut Vec::new()).is_err());
    }

    #[test]
    fn score_round_trip() {
        let mut score = LightingScore::empty(48_000, 2, 256);
        let frame = MusicFrame {
            sample_index: 256,
            time_seconds: 256.0 / 48_000.0,
            loudness: 0.4,
            ..MusicFrame::default()
        };
        score.frames.push(frame);
        score.duration_samples = 48_000;
        score.sections.push(SectionCue {
            start_sample: 0,
            end_sample: 48_000,
            scene: SceneKind::Groove,
            repeat_group: 0,
            intensity: 0.5,
            palette_hue: 0.7,
            palette_chroma: 0.8,
            spatial_mode: SpatialMode::Wave,
            motif_seed: 42,
            anticipation_samples: 0,
            blackout_strength: 0.0,
            narrative_rank: 0.5,
        });
        let mut bytes = Vec::new();
        score.write_to(&mut bytes).unwrap();
        let restored = LightingScore::read_from(&mut bytes.as_slice()).unwrap();
        assert_eq!(score, restored);
    }
}
