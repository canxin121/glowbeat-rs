//! Serializable full-track lighting scores and sample-clock playback.

use std::fs::File;
use std::io::{self, BufReader, BufWriter, Read, Write};
use std::path::Path;

use crate::config::RenderConfig;
use crate::director::{LightDirector, RenderContext, RenderError};
use crate::math::{lerp, smoothstep, wrap01};
use crate::types::{
    AccentEvent, AccentKind, LightPoint, MusicFrame, Rgba, SceneKind, SpatialMode, NUM_BANDS,
    NUM_CHROMA,
};

const MAGIC: &[u8; 8] = b"GLOWGBS1";
const FORMAT_VERSION: u32 = 1;
const SCORE_HEADER_BYTES: usize = 56;
const MUSIC_FRAME_BYTES: usize = 240;
const SECTION_CUE_BYTES: usize = 52;
const ACCENT_EVENT_BYTES: usize = 16;

/// High-level section direction generated by the full-track analyzer.
#[derive(Clone, Debug, PartialEq)]
pub struct SectionCue {
    /// Inclusive beginning in audio samples.
    pub start_sample: u64,
    /// Exclusive end in audio samples.
    pub end_sample: u64,
    /// Inferred scene character.
    pub scene: SceneKind,
    /// Identifier shared by structurally similar/repeated sections.
    pub repeat_group: u16,
    /// Relative section energy in `[0, 1]`.
    pub intensity: f32,
    /// Stable palette hue in turns.
    pub palette_hue: f32,
    /// Palette chroma preference in `[0, 1]`.
    pub palette_chroma: f32,
    /// Spatial motif for this section.
    pub spatial_mode: SpatialMode,
    /// Stable per-section motif seed.
    pub motif_seed: u32,
    /// Number of samples before the boundary used for anticipatory buildup.
    pub anticipation_samples: u64,
    /// Amount of artistic pre-boundary blackout.
    pub blackout_strength: f32,
    /// Global narrative rank; the final/highest climax approaches one.
    pub narrative_rank: f32,
}

impl SectionCue {
    /// Returns true when the sample is inside the section.
    #[must_use]
    pub const fn contains(&self, sample_index: u64) -> bool {
        sample_index >= self.start_sample && sample_index < self.end_sample
    }
}

/// Complete cached analysis and lighting plan for one audio asset.
#[derive(Clone, Debug, PartialEq)]
pub struct LightingScore {
    /// Binary score format version.
    pub version: u32,
    /// Audio sample rate.
    pub sample_rate: u32,
    /// Original number of channels.
    pub channels: u16,
    /// Analysis hop in samples.
    pub analysis_hop: u32,
    /// Total duration in sample frames.
    pub duration_samples: u64,
    /// Dense music-state timeline.
    pub frames: Vec<MusicFrame>,
    /// High-level narrative sections.
    pub sections: Vec<SectionCue>,
    /// Sparse accent index useful for UI/debugging and alternate renderers.
    pub accents: Vec<AccentEvent>,
}

impl LightingScore {
    /// Creates an empty score with valid metadata.
    #[must_use]
    pub fn empty(sample_rate: u32, channels: u16, analysis_hop: u32) -> Self {
        Self {
            version: FORMAT_VERSION,
            sample_rate,
            channels,
            analysis_hop,
            duration_samples: 0,
            frames: Vec::new(),
            sections: Vec::new(),
            accents: Vec::new(),
        }
    }

    /// Writes the score in a compact little-endian binary representation.
    pub fn save<P: AsRef<Path>>(&self, path: P) -> Result<(), ScoreIoError> {
        let file = File::create(path)?;
        let mut writer = BufWriter::new(file);
        self.write_to(&mut writer)?;
        writer.flush()?;
        Ok(())
    }

    /// Loads a score written by [`Self::save`].
    pub fn load<P: AsRef<Path>>(path: P) -> Result<Self, ScoreIoError> {
        let file = File::open(path)?;
        let mut reader = BufReader::new(file);
        Self::read_from(&mut reader)
    }

    /// Returns the exact byte length produced by [`Self::write_to`] without
    /// allocating an intermediate serialization buffer.
    pub fn serialized_len(&self) -> Result<usize, ScoreIoError> {
        self.validate()?;
        let frame_bytes = self
            .frames
            .len()
            .checked_mul(MUSIC_FRAME_BYTES)
            .ok_or(ScoreIoError::TooLarge)?;
        let section_bytes = self
            .sections
            .len()
            .checked_mul(SECTION_CUE_BYTES)
            .ok_or(ScoreIoError::TooLarge)?;
        let accent_bytes = self
            .accents
            .len()
            .checked_mul(ACCENT_EVENT_BYTES)
            .ok_or(ScoreIoError::TooLarge)?;
        SCORE_HEADER_BYTES
            .checked_add(frame_bytes)
            .and_then(|value| value.checked_add(section_bytes))
            .and_then(|value| value.checked_add(accent_bytes))
            .ok_or(ScoreIoError::TooLarge)
    }

    /// Serializes into any writer.
    pub fn write_to<W: Write>(&self, writer: &mut W) -> Result<(), ScoreIoError> {
        self.validate()?;
        writer.write_all(MAGIC)?;
        write_u32(writer, self.version)?;
        write_u32(writer, self.sample_rate)?;
        write_u16(writer, self.channels)?;
        write_u16(writer, 0)?;
        write_u32(writer, self.analysis_hop)?;
        write_u64(writer, self.duration_samples)?;
        write_u64(writer, usize_to_u64(self.frames.len())?)?;
        write_u64(writer, usize_to_u64(self.sections.len())?)?;
        write_u64(writer, usize_to_u64(self.accents.len())?)?;

        for frame in &self.frames {
            write_music_frame(writer, frame)?;
        }
        for section in &self.sections {
            write_section(writer, section)?;
        }
        for accent in &self.accents {
            write_u64(writer, accent.sample_index)?;
            write_u8(writer, accent.kind as u8)?;
            writer.write_all(&[0_u8; 3])?;
            write_f32(writer, accent.strength)?;
        }
        Ok(())
    }

    /// Deserializes from any reader with size and consistency checks.
    pub fn read_from<R: Read>(reader: &mut R) -> Result<Self, ScoreIoError> {
        let mut magic = [0_u8; 8];
        reader.read_exact(&mut magic)?;
        if &magic != MAGIC {
            return Err(ScoreIoError::InvalidFormat("not a GlowBeat score"));
        }
        let version = read_u32(reader)?;
        if version != FORMAT_VERSION {
            return Err(ScoreIoError::UnsupportedVersion(version));
        }
        let sample_rate = read_u32(reader)?;
        let channels = read_u16(reader)?;
        let _reserved = read_u16(reader)?;
        let analysis_hop = read_u32(reader)?;
        let duration_samples = read_u64(reader)?;
        let frame_count = checked_count(read_u64(reader)?, 50_000_000, "frame count")?;
        let section_count = checked_count(read_u64(reader)?, 1_000_000, "section count")?;
        let accent_count = checked_count(read_u64(reader)?, 100_000_000, "accent count")?;
        if sample_rate == 0 || channels == 0 || analysis_hop == 0 {
            return Err(ScoreIoError::InvalidFormat("invalid score metadata"));
        }

        let mut frames = Vec::new();
        frames
            .try_reserve_exact(frame_count)
            .map_err(|_| ScoreIoError::TooLarge)?;
        for _ in 0..frame_count {
            frames.push(read_music_frame(reader)?);
        }
        let mut sections = Vec::new();
        sections
            .try_reserve_exact(section_count)
            .map_err(|_| ScoreIoError::TooLarge)?;
        for _ in 0..section_count {
            sections.push(read_section(reader)?);
        }
        let mut accents = Vec::new();
        accents
            .try_reserve_exact(accent_count)
            .map_err(|_| ScoreIoError::TooLarge)?;
        for _ in 0..accent_count {
            let sample_index = read_u64(reader)?;
            let kind_raw = read_u8(reader)?;
            if kind_raw > AccentKind::Drop as u8 {
                return Err(ScoreIoError::InvalidFormat("unknown accent kind"));
            }
            let kind = AccentKind::from_u8(kind_raw);
            let mut reserved = [0_u8; 3];
            reader.read_exact(&mut reserved)?;
            let strength = read_f32(reader)?;
            accents.push(AccentEvent {
                sample_index,
                kind,
                strength,
            });
        }
        let score = Self {
            version,
            sample_rate,
            channels,
            analysis_hop,
            duration_samples,
            frames,
            sections,
            accents,
        };
        score.validate()?;
        Ok(score)
    }

    /// Validates metadata, numeric values, ordering, and timeline boundaries.
    ///
    /// The same validation runs before serialization and after deserialization,
    /// so malformed cache files cannot create invalid renderer state.
    pub fn validate(&self) -> Result<(), ScoreIoError> {
        if self.version != FORMAT_VERSION {
            return Err(ScoreIoError::UnsupportedVersion(self.version));
        }
        if self.sample_rate == 0 || self.channels == 0 || self.analysis_hop == 0 {
            return Err(ScoreIoError::InvalidFormat("invalid score metadata"));
        }
        if self.frames.len() > 50_000_000 {
            return Err(ScoreIoError::InvalidFormat("frame count"));
        }
        if self.sections.len() > 1_000_000 {
            return Err(ScoreIoError::InvalidFormat("section count"));
        }
        if self.accents.len() > 100_000_000 {
            return Err(ScoreIoError::InvalidFormat("accent count"));
        }
        if self.duration_samples == 0
            && (!self.frames.is_empty() || !self.sections.is_empty() || !self.accents.is_empty())
        {
            return Err(ScoreIoError::InvalidFormat(
                "non-empty timeline has zero duration",
            ));
        }
        for frame in &self.frames {
            if !music_frame_is_finite(frame) {
                return Err(ScoreIoError::InvalidFormat("non-finite music frame"));
            }
            if frame.sample_index > self.duration_samples {
                return Err(ScoreIoError::InvalidFormat("frame exceeds track duration"));
            }
            if frame.meter == 0 || frame.beat_in_bar >= frame.meter {
                return Err(ScoreIoError::InvalidFormat("invalid beat position"));
            }
            if !(0.0..=1.000_1).contains(&frame.beat_phase)
                || !(0.0..=1.000_1).contains(&frame.bar_phase)
            {
                return Err(ScoreIoError::InvalidFormat("invalid rhythmic phase"));
            }
        }
        if self
            .frames
            .windows(2)
            .any(|pair| pair[0].sample_index > pair[1].sample_index)
        {
            return Err(ScoreIoError::InvalidFormat("frames are not time ordered"));
        }
        for section in &self.sections {
            if section.start_sample >= section.end_sample {
                return Err(ScoreIoError::InvalidFormat("empty section cue"));
            }
            if section.end_sample > self.duration_samples {
                return Err(ScoreIoError::InvalidFormat(
                    "section exceeds track duration",
                ));
            }
            if !section_is_finite(section) {
                return Err(ScoreIoError::InvalidFormat("non-finite section cue"));
            }
            if !(0.0..=1.0).contains(&section.intensity)
                || !(0.0..=1.0).contains(&section.palette_chroma)
                || !(0.0..=1.0).contains(&section.blackout_strength)
                || !(0.0..=1.0).contains(&section.narrative_rank)
            {
                return Err(ScoreIoError::InvalidFormat("section value out of range"));
            }
        }
        if self.sections.windows(2).any(|pair| {
            pair[0].start_sample > pair[1].start_sample || pair[0].end_sample > pair[1].start_sample
        }) {
            return Err(ScoreIoError::InvalidFormat(
                "sections are unordered or overlapping",
            ));
        }
        for accent in &self.accents {
            if accent.sample_index > self.duration_samples
                || !accent.strength.is_finite()
                || !(0.0..=2.0).contains(&accent.strength)
            {
                return Err(ScoreIoError::InvalidFormat("invalid accent event"));
            }
        }
        if self
            .accents
            .windows(2)
            .any(|pair| pair[0].sample_index > pair[1].sample_index)
        {
            return Err(ScoreIoError::InvalidFormat("accents are not time ordered"));
        }
        Ok(())
    }

    /// Finds the dense frame at or immediately before a sample.
    #[must_use]
    pub fn frame_index_at(&self, sample_index: u64) -> Option<usize> {
        if self.frames.is_empty() {
            return None;
        }
        match self
            .frames
            .binary_search_by_key(&sample_index, |frame| frame.sample_index)
        {
            Ok(index) => Some(index),
            Err(0) => None,
            Err(index) => Some(index - 1),
        }
    }

    /// Finds the active section at a sample.
    #[must_use]
    pub fn section_index_at(&self, sample_index: u64) -> Option<usize> {
        if self.sections.is_empty() {
            return None;
        }
        let index = match self
            .sections
            .binary_search_by_key(&sample_index, |section| section.start_sample)
        {
            Ok(index) => index,
            Err(0) => 0,
            Err(index) => index - 1,
        };
        self.sections[index].contains(sample_index).then_some(index)
    }
}

/// Sample-clock player for a full-track score.
#[derive(Clone, Debug)]
pub struct ScorePlayer {
    score: LightingScore,
    render_config: RenderConfig,
    light_capacity: usize,
    director: LightDirector,
    next_frame: usize,
    last_sample: Option<u64>,
}

impl ScorePlayer {
    /// Creates a player and preallocates its output history.
    pub fn new(
        score: LightingScore,
        render_config: RenderConfig,
        light_capacity: usize,
    ) -> Result<Self, crate::config::ConfigError> {
        score
            .validate()
            .map_err(|_| crate::config::ConfigError("invalid lighting score"))?;
        if light_capacity == 0 {
            return Err(crate::config::ConfigError(
                "light_capacity must be positive",
            ));
        }
        let director =
            LightDirector::new(render_config.clone(), score.sample_rate, light_capacity)?;
        Ok(Self {
            score,
            render_config,
            light_capacity,
            director,
            next_frame: 0,
            last_sample: None,
        })
    }

    /// Immutable access to the underlying score.
    #[must_use]
    pub const fn score(&self) -> &LightingScore {
        &self.score
    }

    /// Resets temporal state, for example after a player seek.
    ///
    /// A bounded four-second history is replayed to reconstruct palette and
    /// transient-decay state, avoiding a visually cold frame after seeking.
    pub fn seek(&mut self, sample_index: u64) -> Result<(), crate::config::ConfigError> {
        self.director = LightDirector::new(
            self.render_config.clone(),
            self.score.sample_rate,
            self.light_capacity,
        )?;
        if let Some(index) = self.score.frame_index_at(sample_index) {
            let history_samples = u64::from(self.score.sample_rate).saturating_mul(4);
            let history_start = sample_index.saturating_sub(history_samples);
            let first_index = self
                .score
                .frame_index_at(history_start)
                .unwrap_or(0)
                .min(index);
            for frame in &self.score.frames[first_index..=index] {
                self.director.ingest_frame(frame);
            }
            self.next_frame = index + 1;
        } else {
            self.next_frame = 0;
        }
        self.last_sample = Some(sample_index);
        Ok(())
    }

    /// Renders the score at an absolute audio sample position.
    pub fn render(
        &mut self,
        sample_index: u64,
        lights: &[LightPoint],
        output: &mut [Rgba],
    ) -> Result<(), ScorePlayerError> {
        // Reconstruct bounded history after backward seeks, a first render far
        // into the song, or large forward jumps. Normal playback stays on the
        // O(new frames) hot path, while arbitrary player seeks never scan the
        // skipped remainder of a song.
        let large_jump = u64::from(self.score.sample_rate).saturating_mul(8);
        match self.last_sample {
            Some(last) if sample_index < last || sample_index.saturating_sub(last) > large_jump => {
                self.seek(sample_index)?;
            }
            None if sample_index > large_jump => {
                self.seek(sample_index)?;
            }
            _ => {}
        }
        while let Some(frame) = self.score.frames.get(self.next_frame) {
            if frame.sample_index > sample_index {
                break;
            }
            self.director.ingest_frame(frame);
            self.next_frame += 1;
        }
        let context = self.context_at(sample_index);
        self.director
            .render_with_context(sample_index, lights, output, &context)?;
        self.last_sample = Some(sample_index);
        Ok(())
    }

    fn context_at(&self, sample_index: u64) -> RenderContext {
        let Some(section_index) = self.score.section_index_at(sample_index) else {
            return RenderContext::default();
        };
        let section = &self.score.sections[section_index];
        let section_duration = section
            .end_sample
            .saturating_sub(section.start_sample)
            .max(1);
        let progress = (sample_index.saturating_sub(section.start_sample) as f64
            / section_duration as f64) as f32;
        let mut anticipation = 0.0;
        let mut blackout = 0.0;
        if let Some(next) = self.score.sections.get(section_index + 1) {
            let anticipation_start = next.start_sample.saturating_sub(next.anticipation_samples);
            if sample_index >= anticipation_start && sample_index < next.start_sample {
                let anticipation_span = next.start_sample.saturating_sub(anticipation_start).max(1);
                let anticipation_progress = (sample_index.saturating_sub(anticipation_start) as f64
                    / anticipation_span as f64) as f32;
                anticipation = smoothstep(0.0, 1.0, anticipation_progress);
                if next.blackout_strength > 0.0 {
                    let blackout_window = (next.anticipation_samples / 5).max(1);
                    let blackout_start = next.start_sample.saturating_sub(blackout_window);
                    let blackout_span = next.start_sample.saturating_sub(blackout_start).max(1);
                    let blackout_progress = (sample_index.saturating_sub(blackout_start) as f64
                        / blackout_span as f64) as f32;
                    blackout = smoothstep(0.0, 1.0, blackout_progress) * next.blackout_strength;
                }
            }
        }
        // Blend the first part of a section from the previous palette and
        // intensity. Spatial motifs still switch on the musical boundary, while
        // the perceptual color change is continuous instead of a one-frame cut.
        let target_intensity = section_intensity(section);
        let mut palette_hue = wrap01(section.palette_hue);
        let mut intensity = target_intensity;
        if let Some(previous) = section_index
            .checked_sub(1)
            .and_then(|index| self.score.sections.get(index))
        {
            let maximum_blend = u64::from(self.score.sample_rate) * 3 / 5;
            let transition_samples = maximum_blend.min(section_duration / 4).max(1);
            let transition_progress = (sample_index.saturating_sub(section.start_sample) as f64
                / transition_samples as f64) as f32;
            let blend = smoothstep(0.0, 1.0, transition_progress);
            palette_hue = circular_lerp(previous.palette_hue, section.palette_hue, blend);
            intensity = lerp(section_intensity(previous), target_intensity, blend);
        }

        // A subtle section-long evolution prevents static repeated scenes while
        // keeping their palette and motif recognizable.
        let evolution = (progress - 0.5) * 0.028;
        RenderContext {
            palette_hue: Some(palette_hue),
            palette_shift: evolution,
            intensity,
            spatial_mode: Some(section.spatial_mode),
            motif_seed: section.motif_seed,
            anticipation,
            blackout,
        }
    }
}

fn section_intensity(section: &SectionCue) -> f32 {
    lerp(0.82, 1.14, section.intensity) * lerp(0.94, 1.06, section.narrative_rank)
}

fn circular_lerp(start: f32, end: f32, amount: f32) -> f32 {
    let difference = wrap01(end - start + 0.5) - 0.5;
    wrap01(start + difference * amount.clamp(0.0, 1.0))
}

/// Score playback error.
#[derive(Debug)]
pub enum ScorePlayerError {
    /// Invalid renderer configuration while seeking/resetting.
    Config(crate::config::ConfigError),
    /// Output rendering failed.
    Render(RenderError),
}

impl core::fmt::Display for ScorePlayerError {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Config(error) => write!(formatter, "configuration error: {error}"),
            Self::Render(error) => write!(formatter, "render error: {error}"),
        }
    }
}

impl std::error::Error for ScorePlayerError {}

impl From<crate::config::ConfigError> for ScorePlayerError {
    fn from(value: crate::config::ConfigError) -> Self {
        Self::Config(value)
    }
}

impl From<RenderError> for ScorePlayerError {
    fn from(value: RenderError) -> Self {
        Self::Render(value)
    }
}

/// Binary score I/O error.
#[derive(Debug)]
pub enum ScoreIoError {
    /// Underlying filesystem or stream failure.
    Io(io::Error),
    /// Corrupted or inconsistent score data.
    InvalidFormat(&'static str),
    /// Score version newer/older than this build supports.
    UnsupportedVersion(u32),
    /// Collection cannot be represented by the file format.
    TooLarge,
}

impl core::fmt::Display for ScoreIoError {
    fn fmt(&self, formatter: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        match self {
            Self::Io(error) => write!(formatter, "I/O error: {error}"),
            Self::InvalidFormat(message) => write!(formatter, "invalid score: {message}"),
            Self::UnsupportedVersion(version) => {
                write!(formatter, "unsupported score version {version}")
            }
            Self::TooLarge => formatter.write_str("score is too large to serialize"),
        }
    }
}

impl std::error::Error for ScoreIoError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::Io(error) => Some(error),
            _ => None,
        }
    }
}

impl From<io::Error> for ScoreIoError {
    fn from(value: io::Error) -> Self {
        Self::Io(value)
    }
}

fn write_music_frame<W: Write>(writer: &mut W, frame: &MusicFrame) -> io::Result<()> {
    write_u64(writer, frame.sample_index)?;
    write_f64(writer, frame.time_seconds)?;
    for value in [
        frame.loudness,
        frame.peak,
        frame.tonal_confidence,
        frame.spectral_centroid,
        frame.flux,
        frame.onset_low,
        frame.onset_mid,
        frame.onset_high,
        frame.impact,
        frame.bpm,
        frame.beat_phase,
        frame.beat_confidence,
        frame.bar_phase,
        frame.downbeat_confidence,
        frame.energy_trend,
        frame.buildup,
        frame.drop,
        frame.novelty,
    ] {
        write_f32(writer, value)?;
    }
    for value in frame.bands {
        write_f32(writer, value)?;
    }
    for value in frame.chroma {
        write_f32(writer, value)?;
    }
    write_u8(writer, frame.beat_in_bar)?;
    write_u8(writer, frame.meter)?;
    write_u8(writer, u8::from(frame.beat_event))?;
    write_u8(writer, u8::from(frame.downbeat_event))?;
    write_u8(writer, frame.scene as u8)?;
    writer.write_all(&[0_u8; 3])?;
    Ok(())
}

fn read_music_frame<R: Read>(reader: &mut R) -> Result<MusicFrame, ScoreIoError> {
    let sample_index = read_u64(reader)?;
    let time_seconds = read_f64(reader)?;
    let mut scalar = [0.0_f32; 18];
    for value in &mut scalar {
        *value = read_f32(reader)?;
    }
    let mut bands = [0.0_f32; NUM_BANDS];
    for value in &mut bands {
        *value = read_f32(reader)?;
    }
    let mut chroma = [0.0_f32; NUM_CHROMA];
    for value in &mut chroma {
        *value = read_f32(reader)?;
    }
    let beat_in_bar = read_u8(reader)?;
    let meter = read_u8(reader)?;
    let beat_event_raw = read_u8(reader)?;
    let downbeat_event_raw = read_u8(reader)?;
    let scene_raw = read_u8(reader)?;
    if beat_event_raw > 1 || downbeat_event_raw > 1 {
        return Err(ScoreIoError::InvalidFormat("invalid event flag"));
    }
    if scene_raw > SceneKind::Transition as u8 {
        return Err(ScoreIoError::InvalidFormat("unknown scene kind"));
    }
    let beat_event = beat_event_raw != 0;
    let downbeat_event = downbeat_event_raw != 0;
    let scene = SceneKind::from_u8(scene_raw);
    let mut reserved = [0_u8; 3];
    reader.read_exact(&mut reserved)?;
    let frame = MusicFrame {
        sample_index,
        time_seconds,
        loudness: scalar[0],
        peak: scalar[1],
        tonal_confidence: scalar[2],
        spectral_centroid: scalar[3],
        flux: scalar[4],
        onset_low: scalar[5],
        onset_mid: scalar[6],
        onset_high: scalar[7],
        impact: scalar[8],
        bpm: scalar[9],
        beat_phase: scalar[10],
        beat_confidence: scalar[11],
        bar_phase: scalar[12],
        downbeat_confidence: scalar[13],
        energy_trend: scalar[14],
        buildup: scalar[15],
        drop: scalar[16],
        novelty: scalar[17],
        bands,
        chroma,
        beat_in_bar,
        meter,
        beat_event,
        downbeat_event,
        scene,
    };
    if !music_frame_is_finite(&frame) {
        return Err(ScoreIoError::InvalidFormat("non-finite music frame"));
    }
    Ok(frame)
}

fn music_frame_is_finite(frame: &MusicFrame) -> bool {
    frame.time_seconds.is_finite()
        && [
            frame.loudness,
            frame.peak,
            frame.tonal_confidence,
            frame.spectral_centroid,
            frame.flux,
            frame.onset_low,
            frame.onset_mid,
            frame.onset_high,
            frame.impact,
            frame.bpm,
            frame.beat_phase,
            frame.beat_confidence,
            frame.bar_phase,
            frame.downbeat_confidence,
            frame.energy_trend,
            frame.buildup,
            frame.drop,
            frame.novelty,
        ]
        .iter()
        .all(|value| value.is_finite())
        && frame.bands.iter().all(|value| value.is_finite())
        && frame.chroma.iter().all(|value| value.is_finite())
}

fn write_section<W: Write>(writer: &mut W, section: &SectionCue) -> io::Result<()> {
    write_u64(writer, section.start_sample)?;
    write_u64(writer, section.end_sample)?;
    write_u8(writer, section.scene as u8)?;
    write_u8(writer, section.spatial_mode as u8)?;
    write_u16(writer, section.repeat_group)?;
    write_f32(writer, section.intensity)?;
    write_f32(writer, section.palette_hue)?;
    write_f32(writer, section.palette_chroma)?;
    write_u32(writer, section.motif_seed)?;
    write_u64(writer, section.anticipation_samples)?;
    write_f32(writer, section.blackout_strength)?;
    write_f32(writer, section.narrative_rank)?;
    Ok(())
}

fn read_section<R: Read>(reader: &mut R) -> Result<SectionCue, ScoreIoError> {
    let start_sample = read_u64(reader)?;
    let end_sample = read_u64(reader)?;
    let scene_raw = read_u8(reader)?;
    let spatial_raw = read_u8(reader)?;
    if scene_raw > SceneKind::Transition as u8 {
        return Err(ScoreIoError::InvalidFormat("unknown section scene"));
    }
    if spatial_raw > SpatialMode::Sparkle as u8 {
        return Err(ScoreIoError::InvalidFormat("unknown spatial mode"));
    }
    let section = SectionCue {
        start_sample,
        end_sample,
        scene: SceneKind::from_u8(scene_raw),
        spatial_mode: SpatialMode::from_u8(spatial_raw),
        repeat_group: read_u16(reader)?,
        intensity: read_f32(reader)?,
        palette_hue: read_f32(reader)?,
        palette_chroma: read_f32(reader)?,
        motif_seed: read_u32(reader)?,
        anticipation_samples: read_u64(reader)?,
        blackout_strength: read_f32(reader)?,
        narrative_rank: read_f32(reader)?,
    };
    if section.end_sample < section.start_sample || !section_is_finite(&section) {
        return Err(ScoreIoError::InvalidFormat("invalid section cue"));
    }
    Ok(section)
}

fn section_is_finite(section: &SectionCue) -> bool {
    [
        section.intensity,
        section.palette_hue,
        section.palette_chroma,
        section.blackout_strength,
        section.narrative_rank,
    ]
    .iter()
    .all(|value| value.is_finite())
}

fn usize_to_u64(value: usize) -> Result<u64, ScoreIoError> {
    u64::try_from(value).map_err(|_| ScoreIoError::TooLarge)
}

fn checked_count(value: u64, maximum: u64, field: &'static str) -> Result<usize, ScoreIoError> {
    if value > maximum {
        return Err(ScoreIoError::InvalidFormat(field));
    }
    usize::try_from(value).map_err(|_| ScoreIoError::InvalidFormat(field))
}

